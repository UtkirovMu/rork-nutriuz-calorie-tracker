export type TranslationKey = keyof typeof translations;

export function t(section: string, key: string, lang: Language): string {
  const sec = (translations as unknown as Record<string, Record<string, Record<Language, string>>>)[section];
  if (!sec) return key;
  const entry = sec[key];
  if (!entry) return key;
  return entry[lang] || entry['uz'] || key;
}

